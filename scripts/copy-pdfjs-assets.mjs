/**
 * 把 pdf.js 的运行时资源（worker / cmaps / 字体 / wasm / icc）拷贝到 public/pdfjs/，
 * 用于「自托管」部署，避免依赖公网 CDN。
 *
 * 用法：
 *   node scripts/copy-pdfjs-assets.mjs            # 拷到 public/pdfjs/
 *   node scripts/copy-pdfjs-assets.mjs out/assets # 拷到指定目录
 *
 * 配合：
 *   configurePdfjs({
 *     workerSrc: '/pdfjs/build/pdf.worker.min.mjs',
 *     cMapUrl: '/pdfjs/cmaps/',
 *     standardFontDataUrl: '/pdfjs/standard_fonts/',
 *     wasmUrl: '/pdfjs/wasm/',
 *     iccUrl: '/pdfjs/iccs/',
 *   })
 */
import { cp, mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const require = createRequire(import.meta.url);

const outDir = resolve(root, process.argv[2] ?? 'public/pdfjs');

function locatePdfjs() {
  // 优先从 node_modules 解析，兼容 monorepo / pnpm 的符号链接
  try {
    return dirname(require.resolve('pdfjs-dist/package.json'));
  } catch {
    const fallback = join(root, 'node_modules/pdfjs-dist');
    if (existsSync(fallback)) return fallback;
    throw new Error('未找到 pdfjs-dist，请先 npm install');
  }
}

async function sizeOf(path) {
  let total = 0;
  let files = 0;
  const info = await stat(path);
  if (info.isFile()) return { total: info.size, files: 1 };
  const walk = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else {
        total += (await stat(full)).size;
        files += 1;
      }
    }
  };
  await walk(path);
  return { total, files };
}

const pdfjsDir = locatePdfjs();
console.log(`pdfjs-dist: ${pdfjsDir}`);
console.log(`输出目录  : ${outDir}`);

await mkdir(outDir, { recursive: true });

// 只拷运行时真正需要的部分：
//  - build/pdf.worker.min.mjs : worker 本体（约 1MB）
//  - cmaps/                   : 中日韩等 CJK 字体的预定义编码表
//  - standard_fonts/          : 14 种标准字体（未内嵌字体的 PDF 需要）
//  - wasm/                    : JBIG2 / JPEG2000 / QCMS 解码器
//  - iccs/                    : ICC 色彩配置
const targets = [
  ['build/pdf.worker.min.mjs', 'build/pdf.worker.min.mjs'],
  ['cmaps', 'cmaps'],
  ['standard_fonts', 'standard_fonts'],
  ['wasm', 'wasm'],
  ['iccs', 'iccs'],
];

for (const [from, to] of targets) {
  const src = join(pdfjsDir, from);
  const dest = join(outDir, to);
  if (!existsSync(src)) {
    console.warn(`跳过（不存在）: ${from}`);
    continue;
  }
  await mkdir(dirname(dest), { recursive: true });
  await cp(src, dest, { recursive: true });
  const { total, files } = await sizeOf(dest);
  console.log(`✓ ${to.padEnd(28)} ${files} 个文件  ${(total / 1024).toFixed(0)} KB`);
}

// 写一份版本说明，便于排查「库升级了但静态资源没更新」的问题
const pkg = require('pdfjs-dist/package.json');
await writeFile(
  join(outDir, 'VERSION'),
  `pdfjs-dist@${pkg.version}\nGenerated by scripts/copy-pdfjs-assets.mjs\n`,
  'utf8',
);
console.log(`\n完成。pdfjs-dist@${pkg.version} 资源已就绪：${outDir}`);
